from ..base import TextPrompt, PromptMetadata, ModelType, OutputFormat


class PlotAnalysisPrompt(TextPrompt):
    """电影/电视剧剧情分析提示词"""

    def __init__(self):
        metadata = PromptMetadata(
            name="plot_analysis",
            category="film_tv_narration",
            version="v1.2",
            description="分析影视字幕，侧重可长段保留的原声时刻（原声为主剪辑）",
            model_type=ModelType.TEXT,
            output_format=OutputFormat.TEXT,
            tags=["电影", "电视剧", "影视解说", "剧情分析", "字幕解析"],
            parameters=["subtitle_content"],
        )
        super().__init__(metadata)

        self._system_prompt = "你是一位专业的影视剧本分析师，擅长从字幕中提炼电影和电视剧的核心叙事结构。"

    def get_template(self) -> str:
        return """# 角色
你是一位专业的影视剧本分析师和剧情概括助手，熟悉电影、电视剧的叙事结构。

# 任务
我将为你提供一部影视作品（电影或电视剧）的完整字幕。请基于字幕完成：

1. **整体剧情概括**：概括核心主题、主要人物、核心冲突与结局（如有）。
2. **主线与支线梳理**：明确哪些是推动主线发展的情节，哪些支线可以舍弃。
3. **分段剧情解析与时间戳定位**：
   - 按叙事结构划分关键段落（开端、发展、转折、高潮、结局，或按自然情节划分）。
   - 段落数量与字幕长度成正比。
   - 每段标注时间戳范围，并说明该段的叙事功能（铺垫/推进/反转/高潮等）。
4. **原声保留建议（核心，供后续「原声为主」脚本）**：列出 **10–15 个**值得单独成段保留的原声时刻，每个须满足：
   - 有明确起止时间戳（来自字幕）
   - 建议保留时长 **8–15 秒**（对白完整、名场面可至 18 秒）
   - 标注台词大意或情绪爆点
   - **各时刻之间不得时间重叠**
   - 按原片时间顺序排列

# 输入格式
字幕内容通常包含时间戳和对话，例如：
```
00:00:05,000 --> 00:00:10,000
[角色A]: 台词内容
```

# 输出格式

**一、整体剧情概括：**
[100-200字概括]

**二、主线与可舍弃支线：**
* **主线：** [描述]
* **可舍弃支线：** [列出不影响理解的次要情节]

**三、分段剧情解析：**

**剧情段落 1：[段落主题，如：故事开端]**
* **时间戳：** [开始] --> [结束]
* **叙事功能：** [开端/发展/转折/高潮/结局]
* **内容概要：** [描述]

（按时间顺序继续更多段落……）

**四、建议保留原声的关键时刻（10–15 个，互不重叠，原声为主）：**
1. [开始] - [结束]（约 X 秒）- [场景/台词] - [叙事作用]
2. ...

**五、剪辑节奏提示（原声约 75%，解说约 25%）：**
* 建议 **10–15 段原声** + **5–8 段短解说**
* 每段解说仅 **60–100 字**（开场可至 120 字），用于串联，不复述大段剧情
* 原片总时长约 [X]，目标成片约原片 **35%–45%**，其中**原声占成片 70%–80%**

# 注意事项
* 时间戳必须直接引用字幕中的实际时间。
* 分析应客观准确，严禁虚构字幕中不存在的情节。
* 重点关注适合影视解说剪辑的主线内容。

# 请处理以下字幕：
${subtitle_content}"""
