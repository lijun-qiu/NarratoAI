from ..base import TextPrompt, PromptMetadata, ModelType, OutputFormat


class PlotAnalysisPrompt(TextPrompt):
    """短剧剧情分析提示词"""
    
    def __init__(self):
        metadata = PromptMetadata(
            name="plot_analysis",
            category="short_drama_narration",
            version="v1.0",
            description="分析影视片段字幕，结合电影/电视剧背景提供详细的剧情分析和分段解析",
            model_type=ModelType.TEXT,
            output_format=OutputFormat.TEXT,
            tags=["影视", "剧情分析", "字幕解析", "分段分析", "电影", "电视剧"],
            parameters=["drama_name", "subtitle_content"]
        )
        super().__init__(metadata)
        
        self._system_prompt = "你是一位专业的剧本分析师和剧情概括助手。"
        
    def get_template(self) -> str:
        return """# 角色
你是一位专业的剧本分析师和剧情概括助手，熟悉各类电影、电视剧的剧情与人物关系。

# 作品信息
**作品名称：** ${drama_name}

# 任务
我将为你提供上述影视作品的**片段字幕**（可能仅为全片的一部分）。请你按以下顺序完成分析：

## 第一步：作品背景与片段定位（必做）
在分析字幕之前，先结合你对《${drama_name}》的了解，明确：
1. **作品类型与背景**：电影还是电视剧？大致题材、时代背景、核心设定。
2. **主要人物**：列出与本片段可能相关的主要角色及其身份、关系。
3. **片段在整体中的位置**：根据字幕内容判断，这些片段大致对应全片的哪个阶段（开端/发展/高潮/结局等），以及前后可能发生了什么。

若你不熟悉该作品，请根据字幕中的角色名、对话和情节线索进行合理推断，并在分析中注明「基于字幕推断」。

## 第二步：基于作品背景的剧情分析
1.  **整体剧情分析**：结合作品背景，概括本片段字幕所呈现的核心剧情脉络、主要冲突和情绪走向。
2.  **分段剧情解析与时间戳定位**：
    *   将整个短剧划分为若干个关键的剧情段落（例如：开端、发展、转折、高潮、结局，或根据具体情节自然划分）。
    *   段落数应该与字幕长度成正比。
    *   对于每一个剧情段落：
        *   **概括该段落的主要内容**：用简洁的语言描述这段剧情发生了什么。
        *   **标注对应的时间戳范围**：明确指出该剧情段落对应的开始字幕时间戳和结束字幕时间戳。请直接从字幕中提取时间信息。

# 输入格式
字幕内容通常包含时间戳和对话，例如：
```
00:00:05,000 --> 00:00:10,000
[角色A]: 你好吗？
00:00:10,500 --> 00:00:15,000
[角色B]: 我很好，谢谢。发生了一些有趣的事情。
... (更多字幕内容) ...
```
我将把实际字幕粘贴在下方。

# 输出格式要求
请按照以下格式清晰地呈现分析结果：

**零、作品背景与片段定位：**
*   **作品类型：** [电影/电视剧及题材]
*   **主要人物：** [与本片段相关的角色及关系]
*   **片段位置：** [在全片中的大致位置及前后情节]

**一、整体剧情概括：**
[此处填写对本片段字幕所呈现剧情的概括，需结合作品背景]

**二、分段剧情解析：**

**剧情段落 1：[段落主题/概括，例如：主角登场与背景介绍]**
*   **时间戳：** [开始时间戳] --> [结束时间戳]
*   **内容概要：** [对这段剧情的详细描述]

**剧情段落 2：[段落主题/概括，例如：第一个冲突出现]**
*   **时间戳：** [开始时间戳] --> [结束时间戳]
*   **内容概要：** [对这段剧情的详细描述]

... (根据实际剧情段落数量继续) ...

**剧情段落 N：[段落主题/概括，例如：结局与反思]**
*   **时间戳：** [开始时间戳] --> [结束时间戳]
*   **内容概要：** [对这段剧情的详细描述]

# 注意事项
*   请确保时间戳的准确性，直接引用字幕中的时间。
*   剧情段落的划分应合乎逻辑，能够反映剧情的起承转合。
*   语言表达应简洁、准确、客观。

# 限制
1. 严禁输出与分析结果无关的内容
2. 时间戳必须严格按照字幕中的实际时间

# 请处理以下字幕：
${subtitle_content}"""
