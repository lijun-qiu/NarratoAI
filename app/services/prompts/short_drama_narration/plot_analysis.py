from ..base import TextPrompt, PromptMetadata, ModelType, OutputFormat


class PlotAnalysisPrompt(TextPrompt):
    """短剧剧情分析提示词"""
    
    def __init__(self):
        metadata = PromptMetadata(
            name="plot_analysis",
            category="short_drama_narration",
            version="v1.1",
            description="字幕+抽帧联合剧情分析，含正叙/倒叙叙事顺序建议",
            model_type=ModelType.TEXT,
            output_format=OutputFormat.TEXT,
            tags=["短剧", "剧情分析", "字幕解析", "分段分析"],
            parameters=["subtitle_content", "frame_summary"]
        )
        super().__init__(metadata)
        
        self._system_prompt = "你是一位专业的剧本分析师和剧情概括助手。"
        
    def get_template(self) -> str:
        return """# 角色
你是一位专业的剧本分析师和剧情概括助手。

# 任务
我将为你提供一部短剧的完整字幕文本，以及可选的抽帧画面观察。请你**同时阅读字幕与抽帧**，交叉验证后完成：
1.  **整体剧情分析**：概括核心剧情脉络、主要冲突和结局（如有）。
2.  **原片时间线分段**：按字幕 chronology 划分关键剧情段落，每段含时间戳范围与内容概要。
3.  **成片叙事顺序建议**：`_id` 播放顺序可正叙、倒叙、闪回；说明哪些段用倒叙开场、哪些用插叙，以及解说过渡建议。

# 叙事顺序说明（重要）
- **`_id` = 成片播放顺序**；`timestamp` = 原片裁剪区间，**二者独立**
- 原片时间可正叙或倒叙，**按剧情张力安排**，不必随 `_id` 在原片时间轴上递增
- 第 1 段常用全片爆点倒叙原声；第 2 段「宝子们」接入后，可正叙推进或闪回补叙

# 输入格式
字幕内容通常包含时间戳和对话，例如：
```
00:00:05,000 --> 00:00:10,000
[角色A]: 你好吗？
00:00:10,500 --> 00:00:15,000
[角色B]: 我很好，谢谢。发生了一些有趣的事情。
... (更多字幕内容) ...
```
我将把实际字幕粘贴在下方。

# 输出格式要求
请按照以下格式清晰地呈现分析结果：

**一、整体剧情概括：**
[此处填写对整个短剧剧情的概括]

**二、原片时间线分段（按字幕 chronology）：**

**剧情段落 1：[段落主题]**
*   **时间戳：** [开始] --> [结束]
*   **内容概要：** [描述]
*   **画面要点（抽帧）：** [表情/动作/氛围]

... (继续) ...

**三、成片叙事顺序建议（`_id` 播放顺序，可正叙/倒叙/闪回）：**
*   **第 1 段（OST=1）：** [倒叙爆点或其他安排] + 时间戳
*   **第 2 段（OST=0）：** 「宝子们」接入方式 + 时间戳
*   **后续穿插：** [哪些 _id 正叙推进、哪些闪回、过渡句建议]

# 注意事项
*   请确保时间戳的准确性，直接引用字幕中的时间。
*   剧情段落的划分应合乎逻辑，能够反映剧情的起承转合。
*   语言表达应简洁、准确、客观。

# 字幕 × 画面 分析原则（有抽帧观察时须遵守）
- 台词内容、时间戳 → **以字幕为准**
- 人物表情、肢体动作、场景氛围、镜头张力 → **以抽帧观察补充或修正**
- 标注「字幕与画面可形成反差/双关」的时刻（适合保留原声或重点解说）
- 原声保留建议须**同时**考虑台词力度与画面张力

# 限制
1. 严禁输出与分析结果无关的内容
2. 时间戳必须严格按照字幕中的实际时间
3. 严禁虚构字幕或画面中不存在的情节

# 抽帧画面观察（约每 3 秒一帧，请与字幕交叉验证）
<frame_summary>
${frame_summary}
</frame_summary>

# 请处理以下字幕：
${subtitle_content}"""
